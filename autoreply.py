# Детектор ссылки/доступа: юзер вставил в чат свою ссылку вместо импорта в приложение.
import re as _re
_LINK_RE = _re.compile(
    r"(vless://|vmess://|ss://|trojan://|https?://|/sub/|\bsub/\d)",
    _re.IGNORECASE,
)


def looks_like_link(text: str) -> bool:
    return bool(text) and bool(_LINK_RE.search(text))


# Защита от спама: одному юзеру одно и то же правило не чаще раза в 6 часов.
# Кулдаун правил: 6ч. Для ветви «ссылка в чат» — короче: люди повторяют
# попытку в тот же день и раньше получали тишину (22-09-26).
COOLDOWN = 6 * 3600
LINK_COOLDOWN = 15 * 60
_last_hit: dict = {}


def get_autoreply(user_id: int, text: str):
    """Возвращает текст автоответа или None, если ничего не совпало / сработал кулдаун."""
    if not text:
        return None
    hay = _expand(text)
    now = time.time()

    # 0) похоже на ссылку/доступ — подсказываем импорт в приложение, а не чат
    if looks_like_link(text):
        if now - _last_hit.get((user_id, "link"), 0) >= LINK_COOLDOWN:
            _last_hit[(user_id, "link")] = now
            return (
                "🔗 Это ваша <b>ссылка</b>, и она рабочая — просто её место "
                "не в чате, а в приложении. В чат вставлять ничего не нужно.\n\n"
                "<b>Куда вставить (30 секунд):</b>\n"
                "1) Меню → «🔑 МОЙ ДОСТУП» → «📋 Скопировать ссылку» — ссылка ляжет в буфер.\n"
                "2) Откройте приложение.\n"
                "3) «Добавить доступ» / «Импорт из буфера обмена» → вставить.\n"
                "4) Потяните список профилей вниз — появятся каналы. Выберите «🚀 Каскад 443 (WS)».\n\n"
                "Если приложение просит особый формат — в конце ссылки нужен <code>?f=happ</code> — "
                "кнопка «📋 Скопировать ссылку» уже добавляет его сама.\n\n"
                "Одно устройство в чате — не подключение: сам чат интернет не раздаёт. "
                "Если после импорта не заработало — напишите, какой у вас приложение и что пишет, поможем."
            )
        return None
    for name, needles, answer in RULES:
        for needle in needles:
            if needle in hay:
                key = (user_id, name)
                if now - _last_hit.get(key, 0) < COOLDOWN:
                    return None  # уже отвечали недавно — не спамим, уйдёт админу
                _last_hit[key] = now
                return answer
    return None
